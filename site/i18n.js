function detectLanguage() {
  const supported = Object.keys(TRANSLATIONS);
  const params = new URLSearchParams(window.location.search);
  const queryLang = params.get("lang");
  if (queryLang) {
    const normalized = queryLang.toLowerCase().startsWith("zh") ? "zh" : queryLang.toLowerCase().split("-")[0];
    if (supported.includes(normalized)) return normalized;
  }

  const saved = localStorage.getItem("gtv_site_lang");
  if (saved && supported.includes(saved)) return saved;

  const browser = (navigator.language || "en").toLowerCase();
  const shortLang = browser.startsWith("zh") ? "zh" : browser.split("-")[0];
  return supported.includes(shortLang) ? shortLang : "en";
}

function applyTranslations(lang) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  document.documentElement.lang = lang === "zh" ? "zh-Hans" : lang;
  document.title = dict.page_title;

  for (const el of document.querySelectorAll("[data-i18n]")) {
    const key = el.getAttribute("data-i18n");
    if (key && dict[key]) {
      el.textContent = dict[key];
    }
  }

  const select = document.getElementById("lang-select");
  if (select && select.value !== lang) {
    select.value = lang;
  }
}

document.addEventListener("DOMContentLoaded", () => {
  let currentLang = detectLanguage();
  applyTranslations(currentLang);

  const select = document.getElementById("lang-select");
  if (select) {
    select.addEventListener("change", (event) => {
      currentLang = event.target.value;
      localStorage.setItem("gtv_site_lang", currentLang);
      applyTranslations(currentLang);
    });
  }

  for (const btn of document.querySelectorAll(".copy-btn")) {
    btn.addEventListener("click", async () => {
      const text = btn.getAttribute("data-copy");
      if (!text) return;
      try {
        await navigator.clipboard.writeText(text);
        const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
        btn.textContent = dict.btn_copied;
        setTimeout(() => {
          btn.textContent = dict.btn_copy;
        }, 1800);
      } catch {
        // Fallback ignored if clipboard permission is unavailable
      }
    });
  }
});
